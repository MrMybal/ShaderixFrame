"""Regenerate the portable Shaderixel graph slice from locked, unmodified snapshots."""
from pathlib import Path
import json, hashlib, tempfile, argparse, re
from english_ui import translate_cpp
from upstream_paths import acceptable_hashes
root = Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
locked=json.loads((root/'upstream.lock.json').read_text(encoding='utf-8'))
for key,record in locked['files'].items():
    if record.get('externalArtifact') and not (root/'vendor'/key).exists():
        continue
    if key.startswith(('shaderixel/','cydaw2/')) and hashlib.sha256((root/'vendor'/key).read_bytes()).hexdigest() not in acceptable_hashes(key,record):
        raise SystemExit('Modified snapshot: '+key)
(root/'build').mkdir(exist_ok=True)
staging=tempfile.TemporaryDirectory(prefix='shared-components-',dir=root/'build')
generated=Path(staging.name)

h = (root / 'vendor/shaderixel/src/doc/Document.h').read_text(encoding='utf-8')
c = (root / 'vendor/shaderixel/src/doc/Document.cpp').read_text(encoding='utf-8')
def section(s, start, end):
    return s[s.index(start):s.index(end, s.index(start))]
blend = section(h, 'enum class BlendMode', 'enum class DocMode')
bif = section(h, 'struct BlendIf {', 'struct Layer {')
graph = section(h, 'enum class NodeKind', '// Everything except pixels')
graph = graph.replace('EffectInstance fx;', 'CompositionEffect fx;')
# The original graph needs only effect input names. GPU/library effect resolution
# is supplied by ShaderixFrame at the boundary; no graph algorithm is replaced.
contract = """struct CompositionEffect {
    struct Definition { std::vector<std::string> inputs; };
    std::shared_ptr<Definition> definition;
    std::string customCode;
    const Definition* Def() const { return definition.get(); }
};
"""
out = generated / 'ShaderixelComposition.h'
out.write_text('// Generated by tools/extract_composition.py; edit the adapter, not this slice.\n#pragma once\n#include "core/Common.h"\n#include <map>\n#include <set>\n#include <memory>\nnamespace sx {\n' + blend + bif + contract + graph + '}\n', encoding='utf-8')
functions = section(c, 'int NodeInputCount(', '// ------------------------------------------------------------------ document')
functions = functions.replace('static const char* ch[] = {"R", "V", "B", "A"};', 'static const char* ch[] = {"R", "G", "B", "A"};')
(generated / 'ShaderixelComposition.cpp').write_text('// Generated from Shaderixel Document.cpp; graph algorithms unchanged.\n#include "adapters/ShaderixelComposition.h"\nnamespace sx {\n' + functions + '}\n', encoding='utf-8')
# Slang vector select is the only syntax adaptation for D3DCompiler HLSL.
shader = (root / 'vendor/shaderixel/shaders/blend_modes.slang').read_text(encoding='utf-8')
shader = shader.replace('select(b <= 0.0, 0.0, min(1.0, b / max(1.0 - f, 1e-5)))', '(b <= 0.0 ? 0.0 : min(1.0, b / max(1.0 - f, 1e-5)))')
shader = shader.replace('select(b >= 1.0, 1.0, 1.0 - min(1.0, (1.0 - b) / max(f, 1e-5)))', '(b >= 1.0 ? 1.0 : 1.0 - min(1.0, (1.0 - b) / max(f, 1e-5)))')
(generated / 'ShaderixelBlend.h').write_text('// Generated from the locked Shaderixel blend shader.\n#pragma once\nnamespace sf { inline constexpr const char *shaderixelBlendModes = R"SF(' + shader + ')SF"; }\n', encoding='utf-8')

# Reuse the composition calculation itself, including conditional blending,
# clipping and channel masks. Only texture IO and constant bindings change.
composite=(root/'vendor/shaderixel/shaders/composite.slang').read_text(encoding='utf-8')
common=(root/'vendor/shaderixel/shaders/common.slang').read_text(encoding='utf-8')
helpers=section(common,'float SrgbToLinear1','float3 RGBToHSV')+section(common,'float Hash12','float2 Hash22')
weight=section(composite,'float RangeWeight','Texture2D<float4>')
body=section(composite,'    float mask =','    gOut[id.xy] = result;')
body=body.replace('gMask.Load(int3(ap - gMaskOrigin, 0))','Input(2,ctx.px)')
body=body.replace('float3 s = LinearToSrgb(saturate(cs)), u = LinearToSrgb(saturate(cb));','float3 s = sfSrgb ? saturate(cs) : LinearToSrgb(saturate(cs)), u = sfSrgb ? saturate(cb) : LinearToSrgb(saturate(cb));')
params='//@param gMode int 0 0 26\n//@param gOpacity float 1 0 1\n//@param gFlags int 12 0 65535\n//@param sfSrgb bool 0\n'
for group in ('Self','Under'):
 for ch in range(4):
  for k,v in enumerate((0,0,1,1)):params+=f'//@param sf{group}{ch}{k} float {v} 0 1\n'
ranges=''
for group in ('Self','Under'):
 ranges+=f'float4 g{group}Range[4]={{'+','.join('float4('+','.join(f'sf{group}{ch}{k}' for k in range(4))+')' for ch in range(4))+'};\n'
portable=params+shader+helpers+weight+'float4 Effect(EffectContext ctx){int2 ap=ctx.px;float4 base=Premultiply(Input(0,ctx.px)),top=Premultiply(Input(1,ctx.px));\n'+ranges+body+'return Unpremultiply(result);}\n'
with (generated/'ShaderixelBlend.h').open('a',encoding='utf-8') as f:f.write('namespace sf { inline constexpr const char *shaderixelComposite = R"SF('+portable+')SF"; }\n')

# Only parameter captions cross this boundary. All control/card/canvas rendering comes from CyUI.
translations=json.loads((root/'vendor/cydaw2/resources/i18n/fr.json').read_text(encoding='utf-8'))
(generated/'CyDawParameters.h').write_text('// Generated parameter captions; rendering belongs to CyUI.\n#pragma once\n#include <string_view>\nnamespace sf::audio_ui { const char *parameterLabel(std::string_view key); }\n',encoding='utf-8')
with (generated/'CyDawParameters.cpp').open('w',encoding='utf-8') as f:
 f.write('// Generated parameter captions; rendering belongs to CyUI.\n#include "adapters/CyDawParameters.h"\nnamespace sf::audio_ui { const char *parameterLabel(std::string_view key){\n')
 for key in translations:
  if key.startswith('effect.parameter.'):
   label=key.removeprefix('effect.parameter.');label=re.sub(r'([a-z])([A-Z])',r'\1 \2',label).replace('_',' ').title()
   f.write('if(key=='+json.dumps(key)+')return '+json.dumps(label)+';\n')
 f.write('return "Parameter";} }\n')

for p in generated.iterdir():
 p.write_text(translate_cpp(p.read_text(encoding='utf-8')),encoding='utf-8')
outputs={p.name:p.read_bytes() for p in generated.iterdir()}
if args.check:
    for name,data in outputs.items():
        if (root/'src/adapters'/name).read_bytes()!=data:raise SystemExit('Stale extraction: '+name)
    print('Shared component extraction matches every locked source.')
else:
    for name,data in outputs.items():(root/'src/adapters'/name).write_bytes(data)
    print('Regenerated '+str(len(outputs))+' shared component files.')
staging.cleanup()
